export const dictionaries = { en, ko } as const;
export type LocaleKeyType = LocaleKey;
export const REQUIRED_LOCALE_KEYS: readonly LocaleKey[] = Object.keys(en) as LocaleKey[];
export const LOCALE_STORAGE_KEY = "inheritance:locale";

type StorageLike = Pick<Storage, "getItem" | "setItem">;

export function resolveLocalePreference(storage: StorageLike | null, languages: readonly string[]): Locale {
  try {
    const saved = storage?.getItem(LOCALE_STORAGE_KEY);
    if (saved === "en" || saved === "ko") return saved;
  } catch {
    // Storage can be unavailable in private or embedded browser contexts.
  }
  const preferred = languages.find(language => /^(?:ko|en)(?:-|$)/i.test(language.trim())) ?? "";
  return /^ko(?:-|$)/i.test(preferred) ? "ko" : "en";
}

export function persistLocalePreference(locale: Locale, storage: StorageLike | null): boolean {
  try {
    storage?.setItem(LOCALE_STORAGE_KEY, locale);
    return Boolean(storage);
  } catch {
    return false;
  }
}

export function translate(locale: Locale, key: LocaleKey, values: Record<string, string | number> = {}): string {
  const template = dictionaries[locale][key] ?? dictionaries.en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match);
}

// Keep canonical transaction messages independent of the chosen display language.
// Unknown provider diagnostics retain their original text for troubleshooting.
const statusKeys = (Object.keys(en) as LocaleKey[]).filter(key => (key.startsWith("status.") && !key.startsWith("status.error.") || key.startsWith("failure.")) && !en[key].includes("{"));
const messageKeys = new Map<string, LocaleKey>(statusKeys.map(key => [en[key], key]));
const errorKeys = (Object.keys(en) as LocaleKey[]).filter(key => key.startsWith("status.error."));
export function localizeAppMessage(locale: Locale, message: string): string {
  if (!message) return message;
  const legacy: Record<string, LocaleKey> = {
    "A claim is already in the review window.": "failure.AlreadyFiled",
    "The review window is still running.": "failure.ChallengeStillRunning",
    "Claim confirmed. The seven-day review window has started.": "status.claimStarted",
    "Swept the remaining balance to your address": "status.swept",
  };
  if (legacy[message]) return translate(locale, legacy[message]);
  if (locale === "en") return message;
  const key = messageKeys.get(message);
  if (key) return translate(locale, key);
  const notification = /^World App took the request but did not deliver it \((.*)\)\.$/.exec(message);
  if (notification) return translate(locale, "status.notificationsUndelivered", { reason: notification[1] });
  let match = /^(WLD|USDC) strategy fee changed\. Review the current fees and accept them again before continuing\. No new wallet request was sent\.$/.exec(message);
  if (match) return translate(locale, "status.strategyFeeChanged", { symbol: match[1] });
  match = /^Pending… verifying (WLD|USDC) deposit$/.exec(message);
  if (match) return translate(locale, "status.depositPending", { symbol: match[1] });
  match = /^Checked in to all (\d+) active vaults\.$/.exec(message);
  if (match) return translate(locale, "status.allCheckedIn", { count: match[1] });
  match = /^Available receipt shares redeemed to (WLD|USDC)\. Remaining shares, if any, stay in your wallet\.$/.exec(message);
  if (match) return translate(locale, "status.sharesRedeemed", { symbol: match[1] });
  for (const errorKey of errorKeys) {
    const prefix = en[errorKey].split("{reason}")[0];
    if (message.startsWith(prefix)) return translate(locale, errorKey, { reason: localizeAppMessage(locale, message.slice(prefix.length)) });
  }
  return message;
}
